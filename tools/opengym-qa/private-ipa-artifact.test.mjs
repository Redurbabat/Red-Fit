import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { test } from 'node:test';
import { decryptIpa, encryptIpa, generateRecipient } from './private-ipa-artifact.mjs';

test('owner can decrypt an authenticated export; wrong keys and tampering fail without an IPA', async () => {
  const scratch = path.resolve('.red-fit-qa');
  const { mkdir } = await import('node:fs/promises');
  await mkdir(scratch, { recursive: true });
  const root = await mkdtemp(path.join(scratch, 'ipa-envelope-'));
  const owner = path.join(root, 'owner');
  const other = path.join(root, 'other');
  const recipient = await generateRecipient(owner);
  await generateRecipient(other);
  const source = path.join(root, 'synthetic.ipa');
  const original = Buffer.from('PK synthetic IPA fixture, no media or personal data');
  await writeFile(source, original);
  const artifact = path.join(root, 'artifact');
  await encryptIpa(source, recipient + '\n', artifact);
  const ciphertext = path.join(artifact, 'RED-Fit-UNSIGNED.ipa.enc');
  assert.ok(!(await readFile(ciphertext)).includes(original));
  const output = path.join(root, 'decrypted.ipa');
  await decryptIpa(artifact, path.join(owner, 'private.pem'), output);
  assert.deepEqual(await readFile(output), original);
  await assert.rejects(decryptIpa(artifact, path.join(owner, 'private.pem'), output), /already exists/);
  const wrongOutput = path.join(root, 'wrong.ipa');
  await assert.rejects(decryptIpa(artifact, path.join(other, 'private.pem'), wrongOutput), /Wrong recipient/);
  await assert.rejects(stat(wrongOutput), { code: 'ENOENT' });
  const modified = await readFile(ciphertext);
  modified[0] ^= 1;
  await writeFile(ciphertext, modified);
  const tamperedOutput = path.join(root, 'tampered.ipa');
  await assert.rejects(decryptIpa(artifact, path.join(owner, 'private.pem'), tamperedOutput));
  await assert.rejects(stat(tamperedOutput), { code: 'ENOENT' });
  await assert.rejects(encryptIpa(source, 'invalid-key', path.join(root, 'bad')), /SPKI/);
  await assert.rejects(encryptIpa(source, recipient, artifact), { code: 'EEXIST' });
  await assert.rejects(generateRecipient(owner), { code: 'EEXIST' });
});
